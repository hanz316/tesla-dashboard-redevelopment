#!/usr/bin/env python3
"""EnvironmentTimeSystem: which environment the screen shows, and when.

Horizon must not be permanently night, and it must not switch: the review is
explicit that 17:59 day / 18:00 night is a failure. This module defines four
phases (DAWN, DAY, DUSK, NIGHT), the weights that blend them as a function of
local time, the palette each phase uses, and the offline sunrise/sunset
schedule that decides when the transitions happen.

Everything is offline. Priority for the schedule:

  1. calculated sunrise/sunset from date, latitude, longitude and timezone,
     using the standard solar-declination approximation (no network);
  2. a monthly regional profile for Southern Ontario / GTA, generated by the
     same model for the region centroid;
  3. a fixed safe fallback (07:00 / 19:00) when even that is unavailable.

Nothing about the owner location is stored: the provider takes coordinates
only if the caller already has them.

Usage:
    python3 tools/assets/horizon_v5_environment_time.py --json assets/ui/horizon_v5_environment.json
    python3 tools/assets/horizon_v5_environment_time.py --at "2026-01-15 08:10"
    python3 tools/assets/horizon_v5_environment_time.py --seasonal
"""

import argparse
import json
import math
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "assets", "ui", "horizon_v5_environment.json")

PHASES = ["night", "dawn", "day", "dusk"]

# Transition windows in minutes around each event. Both are far wider than one
# frame of change, which is what makes the blend continuous instead of a switch:
# smoothstep has a maximum slope of 1.5 per window, so a 105 minute window
# cannot move a phase weight by more than 0.015 in a minute.
DAWN_WINDOW_MIN = (90, 105)
DUSK_WINDOW_MIN = (105, 90)

REGION = {"name": "Southern Ontario (GTA centroid)",
          "latitude": 43.70, "longitude": -79.40,
          "utc_offset_hours": -5.0, "dst": True}

SAFE_FALLBACK = {"sunrise_minutes": 7 * 60, "sunset_minutes": 19 * 60}

